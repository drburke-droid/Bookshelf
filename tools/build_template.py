"""Build bookshelf_template.blend from scratch.

    python tools/fetch_assets.py <assets_dir> models potted_plant_04 standing_picture_frame_02 \
        ceramic_vase_01 carved_wooden_elephant marble_bust_01 horse_statue_01 concrete_cat_statue
    python tools/fetch_assets.py <assets_dir> textures oak_veneer_01
    blender -b --factory-startup --python tools/build_template.py -- <assets_dir> <output.blend>

Everything in the result is either generated by bookshelf_generator.py or a CC0 asset from
polyhaven.com, so the file can be shared freely.
"""
import math
import os
import runpy
import sys

import bpy
from mathutils import Matrix, Vector

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args = sys.argv[sys.argv.index("--") + 1:]
ASSETS, OUTPUT = os.path.abspath(args[0]), os.path.abspath(args[1])
GENERATOR = os.path.join(ROOT, "bookshelf_generator.py")
SAMPLE = os.path.join(ROOT, "sample", "goodreads_sample.csv")
PACK_DIR = os.path.join(ASSETS, "_packed")
os.makedirs(PACK_DIR, exist_ok=True)

# name in the file, Poly Haven asset, real-world height to scale to (m), turn (degrees), face budget
PROPS = [
    ("Succulent", "potted_plant_04", 0.17, 0, 40000),
    ("Picture Frame", "standing_picture_frame_02", 0.20, 0, 20000),
    ("Vase", "ceramic_vase_01", 0.20, 0, 20000),
    ("Elephant", "carved_wooden_elephant", 0.15, 0, 30000),
    ("Bust", "marble_bust_01", 0.22, 0, 30000),
    ("Horse", "horse_statue_01", 0.21, 0, 30000),
    ("Cat", "concrete_cat_statue", 0.17, 0, 30000),
]
TEXTURE_SIZE = 512

gen = runpy.run_path(GENERATOR, run_name="__main__")
scene = bpy.context.scene

# ---------------------------------------------------------------- clean start
for ob in list(bpy.data.objects):
    bpy.data.objects.remove(ob)
for coll in list(bpy.data.collections):
    bpy.data.collections.remove(coll)
for block in (bpy.data.meshes, bpy.data.materials, bpy.data.lights, bpy.data.cameras, bpy.data.images):
    for item in list(block):
        if item.users == 0:
            block.remove(item)


# ---------------------------------------------------------------- textures
def shrink_and_pack(img, size=TEXTURE_SIZE):
    """Downscale an image, re-save it as JPEG (PNG when it carries alpha) and pack it."""
    if img.source != "FILE" or not img.has_data and img.size[0] == 0:
        return
    w, h = img.size
    if w == 0 or h == 0:
        return
    uses_alpha = any(link.from_socket.name == "Alpha"
                     for mat in bpy.data.materials if mat.node_tree
                     for link in mat.node_tree.links
                     if getattr(link.from_node, "image", None) == img)
    if max(w, h) > size:
        factor = size / max(w, h)
        img.scale(max(1, round(w * factor)), max(1, round(h * factor)))
    ext, fmt = (".png", "PNG") if uses_alpha else (".jpg", "JPEG")
    stem = os.path.splitext(os.path.basename(bpy.path.abspath(img.filepath)))[0]
    path = os.path.join(PACK_DIR, stem + ext)
    img.filepath_raw = path
    img.file_format = fmt
    img.save(quality=88)
    img.pack()
    img.filepath = "//textures/" + stem + ext
    for packed in img.packed_files:          # don't keep the build machine's folder names in the file
        packed.filepath = img.filepath
    img.name = stem + ext


# ---------------------------------------------------------------- decorations
root = gen["ensure_collection"](gen["COLL_ROOT"], scene.collection)
props_root = gen["ensure_collection"](gen["COLL_PROPS"], root)

for name, asset, target_h, turn, max_faces in PROPS:
    path = os.path.join(ASSETS, asset, asset + ".blend")
    with bpy.data.libraries.load(path) as (src, dst):
        dst.objects = list(src.objects)
    coll = bpy.data.collections.new(name)
    props_root.children.link(coll)
    meshes = [ob for ob in dst.objects if ob is not None and ob.type == "MESH"]
    for ob in dst.objects:
        if ob is not None and ob.type != "MESH":
            bpy.data.objects.remove(ob)
    for ob in meshes:
        coll.objects.link(ob)
    bpy.context.view_layer.update()

    # Bake transforms into the mesh, thin out very dense meshes.
    depsgraph = bpy.context.evaluated_depsgraph_get()
    total_faces = sum(len(ob.data.polygons) for ob in meshes)
    for ob in meshes:
        world = ob.matrix_world.copy()
        if total_faces > max_faces:
            mod = ob.modifiers.new("Decimate", "DECIMATE")
            mod.ratio = max_faces / total_faces
            depsgraph.update()
            new_mesh = bpy.data.meshes.new_from_object(ob.evaluated_get(depsgraph))
            ob.modifiers.remove(mod)
        else:
            new_mesh = ob.data.copy()
        old = ob.data
        ob.parent = None
        ob.data = new_mesh
        if old.users == 0:
            bpy.data.meshes.remove(old)
        ob.data.transform(world)
        ob.matrix_world = Matrix.Identity(4)

    # Stand it on the origin, facing -Y, at a sensible size for a shelf.
    lo = Vector((1e9, 1e9, 1e9))
    hi = Vector((-1e9, -1e9, -1e9))
    for ob in meshes:
        for v in ob.data.vertices:
            lo = Vector((min(lo.x, v.co.x), min(lo.y, v.co.y), min(lo.z, v.co.z)))
            hi = Vector((max(hi.x, v.co.x), max(hi.y, v.co.y), max(hi.z, v.co.z)))
    scale = target_h / (hi.z - lo.z)
    fix = (Matrix.Rotation(math.radians(turn), 4, "Z") @ Matrix.Scale(scale, 4)
           @ Matrix.Translation((-(lo.x + hi.x) / 2, -(lo.y + hi.y) / 2, -lo.z)))
    for ob in meshes:
        ob.data.transform(fix)
        ob.data.update()
        ob.name = f"{name} {ob.name}"[:60]
    print(f"PROP {name}: {total_faces} -> {sum(len(o.data.polygons) for o in meshes)} faces, "
          f"size {[round(v * scale, 3) for v in (hi - lo)]}")

for img in list(bpy.data.images):
    shrink_and_pack(img)

# ---------------------------------------------------------------- shelf wood (Poly Haven oak veneer)
wood = gen["new_material"](gen["MAT_WOOD"])
nodes, links = wood.node_tree.nodes, wood.node_tree.links
out = nodes.new("ShaderNodeOutputMaterial")
out.location = (600, 0)
bsdf = nodes.new("ShaderNodeBsdfPrincipled")
bsdf.location = (300, 0)
links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
coord = nodes.new("ShaderNodeTexCoord")
coord.location = (-1100, 0)
info = nodes.new("ShaderNodeObjectInfo")
info.location = (-1100, -300)
offset = nodes.new("ShaderNodeVectorMath")
offset.operation = "ADD"
offset.location = (-900, 0)
spread = nodes.new("ShaderNodeMath")
spread.operation = "MULTIPLY"
spread.location = (-900, -300)
spread.inputs[1].default_value = 7.0
links.new(info.outputs["Random"], spread.inputs[0])
links.new(coord.outputs["Object"], offset.inputs[0])
links.new(spread.outputs[0], offset.inputs[1])
mapping = nodes.new("ShaderNodeMapping")
mapping.location = (-700, 0)
mapping.inputs["Scale"].default_value = (0.9, 0.9, 0.9)
links.new(offset.outputs[0], mapping.inputs["Vector"])


def wood_map(suffix, y, colour):
    img = bpy.data.images.load(os.path.join(ASSETS, "oak_veneer_01", f"oak_veneer_01_{suffix}.jpg"))
    if not colour:
        img.colorspace_settings.name = "Non-Color"
    shrink_and_pack(img, 1024)
    tex = nodes.new("ShaderNodeTexImage")
    tex.image = img
    tex.projection = "BOX"
    tex.projection_blend = 0.2
    tex.location = (-450, y)
    links.new(mapping.outputs["Vector"], tex.inputs["Vector"])
    return tex


diff = wood_map("diff", 300, True)
rough = wood_map("rough", 0, False)
nor = wood_map("nor", -300, False)
tone = nodes.new("ShaderNodeHueSaturation")       # a little darker and warmer than raw oak
tone.location = (-100, 300)
tone.inputs["Saturation"].default_value = 1.1
tone.inputs["Value"].default_value = 0.55
links.new(diff.outputs["Color"], tone.inputs["Color"])
links.new(tone.outputs["Color"], bsdf.inputs["Base Color"])
links.new(rough.outputs["Color"], bsdf.inputs["Roughness"])
normal = nodes.new("ShaderNodeNormalMap")
normal.location = (-100, -300)
normal.inputs["Strength"].default_value = 0.6
links.new(nor.outputs["Color"], normal.inputs["Color"])
links.new(normal.outputs["Normal"], bsdf.inputs["Normal"])

# ---------------------------------------------------------------- world and render settings
world = bpy.data.worlds.get("World") or bpy.data.worlds.new("World")
scene.world = world
try:
    world.use_nodes = True
except Exception:  # noqa: BLE001
    pass
bg = world.node_tree.nodes.get("Background")
if bg is not None:
    bg.inputs["Color"].default_value = (0.55, 0.47, 0.40, 1.0)
    bg.inputs["Strength"].default_value = 0.35

scene.render.engine = "CYCLES"
scene.cycles.device = "GPU"            # falls back to the CPU when no GPU is set up
scene.cycles.samples = 96
scene.cycles.use_adaptive_sampling = True
scene.cycles.adaptive_threshold = 0.02
scene.cycles.use_denoising = True
scene.render.resolution_x = 1920
scene.render.resolution_y = 1080
scene.render.resolution_percentage = 100
scene.render.image_settings.file_format = "PNG"
scene.render.filepath = "//bookshelf.png"
scene.unit_settings.system = "METRIC"
try:
    scene.view_settings.view_transform = "AgX"
    scene.view_settings.look = "AgX - Medium High Contrast"
except TypeError:
    pass

# ---------------------------------------------------------------- script and sample list inside the file
with open(GENERATOR, encoding="utf-8") as handle:
    script = bpy.data.texts.new("bookshelf_generator.py")
    script.from_string(handle.read())
    script.use_module = True           # "Register": runs when the file opens (if scripts are allowed)
    script.cursor_set(0)
with open(SAMPLE, encoding="utf-8") as handle:
    bpy.data.texts.new(gen["SAMPLE_TEXT"]).from_string(handle.read())

# ---------------------------------------------------------------- first bookshelf, from the sample list
gen["ensure_collection"](gen["COLL_PROPS"], root, exclude=True)
result = bpy.ops.bookshelf.build()
print("BUILD", result, scene.bookshelf.status)

# ---------------------------------------------------------------- viewport: sidebar open, looking through the camera
for screen in bpy.data.screens:
    for area in screen.areas:
        for space in area.spaces:
            if space.type == "VIEW_3D":
                space.show_region_ui = True
                space.region_3d.view_perspective = "CAMERA"
                space.shading.type = "SOLID"
                space.shading.color_type = "OBJECT"
                space.shading.light = "STUDIO"
                space.overlay.show_floor = False
                space.overlay.show_axis_x = False
                space.overlay.show_axis_y = False
                space.overlay.show_cursor = False
            elif space.type == "TEXT_EDITOR":
                space.text = script
        if area.type == "VIEW_3D":
            for region in area.regions:
                if region.type == "UI":
                    try:
                        region.active_panel_category = "Bookshelf"
                    except Exception as err:  # noqa: BLE001
                        print("TAB", screen.name, err)

for block in (bpy.data.meshes, bpy.data.materials, bpy.data.images, bpy.data.node_groups):
    for item in list(block):
        if item.users == 0:
            block.remove(item)

bpy.ops.wm.save_as_mainfile(filepath=OUTPUT, compress=True)
print("SAVED", OUTPUT, f"{os.path.getsize(OUTPUT) / 1e6:.1f} MB")
